#!/usr/bin/env python3
"""Fill the RESULTS block of README.md from results/rq1_<gen>.csv and results/rq2_<gen>.csv.

No number in the README results block is typed by hand: re-run this script after every
`python analysis/analyze.py` and the README follows the data. Also draws docs/rq2_auroc.png
(needs matplotlib, `pip install -e ".[analysis]"`).

    python scripts/update_readme_results.py --generator local
"""
from __future__ import annotations

import argparse
import csv
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from rctaudit.metrics import wilson_ci  # noqa: E402

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
GROUPS = [("unsupported_rate_numeric_hard", "Numeric, hard (percentages, decimals, comparisons)"),
          ("unsupported_rate_numeric_easy", "Numeric, easy (bare integers, p-values)"),
          ("unsupported_rate_non_numeric", "Non-numeric"),
          ("unsupported_rate_all", "**All claims** (re-weighted to the claim pool)")]
ERROR_TYPES = ["Unsupported-number", "Unsupported-claim", "Misattributed", "Direction-wrong",
               "Overgeneralized", "Derived-wrong"]


def read_rows(path: Path) -> list[dict]:
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def num(x) -> float | None:
    try:
        return float(x) if x not in (None, "") else None
    except ValueError:
        return None


wilson = wilson_ci


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def error_count(row: dict) -> int | None:
    m = re.match(r"(\d+) unsupported", row.get("note", ""))
    if m:
        return int(m.group(1))
    m = re.search(r"Raw sheet rate ([\d.]+)", row.get("note", ""))
    return round(float(m.group(1)) * int(row["n"])) if m else None


def rq1_table(rq1: list[dict]) -> str:
    by = {r["quantity"]: r for r in rq1}
    lines = ["| Claim group | Unsupported rate | 95% CI | Labelled claims | Unsupported |", "|---|---:|---:|---:|---:|"]
    for key, label in GROUPS:
        r = by.get(key)
        if not r or num(r["estimate"]) is None:
            continue
        n, k = int(r["n"]), error_count(r)
        lo, hi = num(r["ci_lo"]), num(r["ci_hi"])
        if k == 0:                                   # a bootstrap of zero events is always [0, 0]: use Wilson
            lo, hi = wilson(0, n)
            ci = f"{pct(lo)}-{pct(hi)} (Wilson)"
        else:
            ci = f"{pct(lo)}-{pct(hi)}"
        lines.append(f"| {label} | {pct(num(r['estimate']))} | {ci} | {n} | {'' if k is None else k} |")
    return "\n".join(lines)


def error_type_table(rq1: list[dict]) -> str:
    by = {r["quantity"]: r for r in rq1}
    rows = []
    for t in ERROR_TYPES:
        r = by.get(f"share_{t}")
        if r and num(r["estimate"]):
            rows.append(f"| {t} | {round(num(r['estimate']) * int(r['n']))} |")
    if not rows:
        return "_No unsupported claims in the labelled sample._"
    return "\n".join(["| Error type | Claims |", "|---|---:|"] + rows)


def rule_sentence(rq1: list[dict]) -> str:
    by = {r["quantity"]: r for r in rq1}
    r = by.get("rule_supported_but_human_unsupported")
    if not r or num(r["estimate"]) is None:
        return ""
    return (f"Of the {r['n']} claims the rule-based number check called *supported*, {pct(num(r['estimate']))} were judged "
            "unsupported by the human labeller: the check sees whether a number is in the abstract, not what it is attached to.")


def rq2_table(rq2: list[dict]) -> str:
    lines = ["| Signal | Claims | Unsupported | AUROC | 95% CI | Reading |", "|---|---:|---:|---:|---:|---|"]
    for r in rq2:
        if r["subset"] != "own":
            continue
        n, k, a = r["n"], r["n_unsupported"], num(r["auroc"])
        if a is None:
            lines.append(f"| {r['signal']} | {n} | {k or ''} | n/a | n/a | not enough labelled claims |")
            continue
        reading = "descriptive only (< 10 unsupported)" if "descriptive" in r["note"] else "wide interval"
        lines.append(f"| {r['signal']} | {n} | {k} | {a:.2f} | {num(r['auroc_lo']):.2f}-{num(r['auroc_hi']):.2f} | {reading} |")
    return "\n".join(lines)


def build_block(rq1: list[dict], rq2: list[dict], gen: str, figure: str | None) -> str:
    n = next((int(r["n"]) for r in rq1 if r["quantity"] == "unsupported_rate_all"), 0)
    parts = [START,
             f"<!-- generated by scripts/update_readme_results.py from results/rq1_{gen}.csv and results/rq2_{gen}.csv; "
             "do not edit by hand -->",
             f"**{n} human-labelled claims, one annotator, judged against the abstract only.** Intervals are cluster "
             "bootstraps by abstract; AUROC higher = the signal ranks unsupported claims as less confident.",
             "", "#### RQ1: how many claims are unsupported?", "", rq1_table(rq1), "",
             error_type_table(rq1), ""]
    rs = rule_sentence(rq1)
    if rs:
        parts += [rs, ""]
    parts += ["#### RQ2: which confidence signal detects them?", "", rq2_table(rq2), ""]
    if figure:
        parts += [f"![AUROC per signal]({figure})", ""]
    parts.append(END)
    return "\n".join(parts)


def replace_block(readme: str, block: str) -> str:
    i, j = readme.find(START), readme.find(END)
    if i < 0 or j < i:
        raise SystemExit(f"README has no {START} ... {END} block")
    return readme[:i] + block + readme[j + len(END):]


def draw_figure(rq2: list[dict], out: Path) -> bool:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not installed: figure skipped", file=sys.stderr)
        return False
    rows = [r for r in rq2 if r["subset"] == "own" and num(r["auroc"]) is not None]
    if not rows:
        return False
    rows = rows[::-1]
    fig, ax = plt.subplots(figsize=(7.2, 0.42 * len(rows) + 1.3), dpi=160, facecolor="white")
    for y, r in enumerate(rows):
        a, lo, hi = num(r["auroc"]), num(r["auroc_lo"]), num(r["auroc_hi"])
        weak = "descriptive" in r["note"]
        ax.plot([lo, hi], [y, y], color="#8a94a6", lw=2, solid_capstyle="round")
        ax.plot([a], [y], "o", ms=7, mfc="white" if weak else "#2563eb", mec="#2563eb", mew=1.8)
    ax.axvline(0.5, color="#c0392b", ls="--", lw=1)
    ax.set_yticks(range(len(rows)), [f"{r['signal']}  (n={r['n']}, {r['n_unsupported']} unsupported)" for r in rows], fontsize=7.5)
    ax.set_xlim(0, 1)
    ax.set_xlabel("AUROC (dashed = chance; hollow = under 10 unsupported)", fontsize=7.5)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    fig.suptitle("Which confidence signal separates unsupported claims?", x=0.01, ha="left", fontsize=10, fontweight="bold")
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, facecolor="white")
    return True


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--generator", default="local")
    ap.add_argument("--readme", default=str(ROOT / "README.md"))
    ap.add_argument("--results", default=str(ROOT / "results"))
    ap.add_argument("--figure", default=str(ROOT / "docs" / "rq2_auroc.png"))
    a = ap.parse_args(argv)
    res = Path(a.results)
    rq1, rq2 = read_rows(res / f"rq1_{a.generator}.csv"), read_rows(res / f"rq2_{a.generator}.csv")
    fig_path = Path(a.figure)
    drawn = draw_figure(rq2, fig_path)
    rel = Path(os.path.relpath(fig_path.resolve(), Path(a.readme).resolve().parent)).as_posix()
    readme = Path(a.readme)
    readme.write_text(replace_block(readme.read_text(encoding="utf-8"), build_block(rq1, rq2, a.generator, rel if drawn else None)),
                      encoding="utf-8")
    print(f"updated {readme} from results/rq1_{a.generator}.csv, rq2_{a.generator}.csv" + (f"; figure {a.figure}" if drawn else ""))


if __name__ == "__main__":
    main()
